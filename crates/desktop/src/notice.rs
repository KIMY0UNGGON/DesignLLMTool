//! The one message the workbench shows at a time. A message exists only because an action or a
//! load really failed (or finished with a result the screen cannot show), and it never outlives
//! the situation that raised it: a later success of the same call, any new user action, opening
//! another document, or its own timeout removes it.

use std::time::{Duration, Instant};

const INFO_LIFETIME: Duration = Duration::from_secs(4);
const WARNING_LIFETIME: Duration = Duration::from_secs(8);
const ERROR_LIFETIME: Duration = Duration::from_secs(12);

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Severity {
    Info,
    Warning,
    Error,
}

#[derive(Clone, Debug)]
pub struct Notice {
    pub severity: Severity,
    pub text: String,
    origin: Option<String>,
    raised: Instant,
    acknowledgement_keys: Vec<String>,
}

impl Notice {
    fn lifetime(&self) -> Duration {
        match self.severity {
            Severity::Info => INFO_LIFETIME,
            Severity::Warning => WARNING_LIFETIME,
            Severity::Error => ERROR_LIFETIME,
        }
    }

    pub fn requires_acknowledgement(&self) -> bool {
        !self.acknowledgement_keys.is_empty()
    }

    /// The method whose later success takes this notice away (`Notices::succeeded`), if any.
    pub fn origin(&self) -> Option<&str> {
        self.origin.as_deref()
    }
}

#[derive(Default)]
pub struct Notices {
    current: Option<Notice>,
    workspace: Option<Notice>,
}

impl Notices {
    /// A failed call. `origin` is the RPC method, so that the same method succeeding later removes it.
    pub fn error(&mut self, text: impl Into<String>, origin: Option<&str>, now: Instant) {
        self.current = Some(Notice {
            severity: Severity::Error,
            text: text.into(),
            origin: origin.map(str::to_owned),
            raised: now,
            acknowledgement_keys: Vec::new(),
        });
    }

    /// The result of an action whose effect is not visible on the canvas (a file was written).
    pub fn info(&mut self, text: impl Into<String>, now: Instant) {
        self.current = Some(Notice {
            severity: Severity::Info,
            text: text.into(),
            origin: None,
            raised: now,
            acknowledgement_keys: Vec::new(),
        });
    }

    /// A short warning generated by a successful edit or save.
    pub fn warning(&mut self, text: impl Into<String>, now: Instant) {
        self.current = Some(Notice {
            severity: Severity::Warning,
            text: text.into(),
            origin: None,
            raised: now,
            acknowledgement_keys: Vec::new(),
        });
    }

    /// A workspace warning stays visible until the user confirms it. Transient messages may temporarily cover it.
    pub fn workspace_warning(&mut self, text: impl Into<String>, keys: Vec<String>, now: Instant) {
        if keys.is_empty() {
            return;
        }
        let text = text.into();
        if self.workspace.as_ref().is_some_and(|notice| notice.text == text && notice.acknowledgement_keys == keys) {
            return;
        }
        self.workspace = Some(Notice {
            severity: Severity::Warning,
            text,
            origin: None,
            raised: now,
            acknowledgement_keys: keys,
        });
    }

    /// Confirms the current persistent workspace warning and returns its session-only acknowledgement keys.
    pub fn acknowledge_workspace(&mut self) -> Vec<String> {
        self.workspace.take().map_or_else(Vec::new, |notice| notice.acknowledgement_keys)
    }

    pub fn clear(&mut self) {
        self.current = None;
        self.workspace = None;
    }

    /// Clears temporary messages without dismissing workspace warnings that require confirmation.
    pub fn clear_transient(&mut self) {
        self.current = None;
    }

    /// `method` returned successfully: an error that it raised earlier is obsolete.
    pub fn succeeded(&mut self, method: &str) {
        if self
            .current
            .as_ref()
            .is_some_and(|notice| notice.origin.as_deref() == Some(method))
        {
            self.current = None;
        }
    }

    pub fn current(&self, now: Instant) -> Option<&Notice> {
        self.current
            .as_ref()
            .filter(|notice| now.saturating_duration_since(notice.raised) < notice.lifetime())
            .or(self.workspace.as_ref())
    }

    /// Time until the visible message times out, so the window can repaint exactly then.
    pub fn expires_in(&self, now: Instant) -> Option<Duration> {
        self.current.as_ref().filter(|notice| now.saturating_duration_since(notice.raised) < notice.lifetime()).map(|notice| {
            notice
                .lifetime()
                .saturating_sub(now.saturating_duration_since(notice.raised))
        })
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn nothing_is_shown_until_something_fails() {
        let notices = Notices::default();
        assert!(notices.current(Instant::now()).is_none());
        assert!(notices.expires_in(Instant::now()).is_none());
    }

    #[test]
    fn an_error_is_shown_and_times_out() {
        let start = Instant::now();
        let mut notices = Notices::default();
        notices.error("저장하지 못했습니다", Some("artifact.save"), start);
        let shown = notices.current(start + Duration::from_secs(1)).expect("visible");
        assert_eq!(shown.severity, Severity::Error);
        assert_eq!(shown.text, "저장하지 못했습니다");
        assert!(notices.current(start + ERROR_LIFETIME).is_none());
        assert_eq!(notices.expires_in(start), Some(ERROR_LIFETIME));
    }

    #[test]
    fn the_same_call_succeeding_removes_its_error_but_other_calls_do_not() {
        let start = Instant::now();
        let mut notices = Notices::default();
        notices.error("미리보기를 불러오지 못했습니다", Some("render.get"), start);
        notices.succeeded("context.read");
        assert!(notices.current(start).is_some());
        notices.succeeded("render.get");
        assert!(notices.current(start).is_none());
    }

    #[test]
    fn an_error_without_an_origin_is_removed_only_by_clear_or_timeout() {
        let start = Instant::now();
        let mut notices = Notices::default();
        notices.error("입력 내용을 확인해 주세요", None, start);
        notices.succeeded("changes.apply");
        assert!(notices.current(start).is_some());
        notices.clear();
        assert!(notices.current(start).is_none());
    }

    #[test]
    fn a_result_message_replaces_an_older_error_and_expires_sooner() {
        let start = Instant::now();
        let mut notices = Notices::default();
        notices.error("실패", Some("artifact.export"), start);
        notices.info("내보냈습니다", start);
        let shown = notices.current(start).expect("visible");
        assert_eq!(shown.severity, Severity::Info);
        assert!(notices.current(start + INFO_LIFETIME).is_none());
        assert_eq!(notices.expires_in(start + Duration::from_secs(1)), Some(INFO_LIFETIME - Duration::from_secs(1)));
    }

    #[test]
    fn workspace_warning_survives_time_and_transient_messages_until_confirmed() {
        let start = Instant::now();
        let mut notices = Notices::default();
        notices.workspace_warning("작업공간 상태를 확인해 주세요", vec!["w:key".into()], start);
        let shown = notices.current(start + Duration::from_secs(60)).expect("persistent warning remains visible");
        assert_eq!(shown.severity, Severity::Warning);
        assert!(shown.requires_acknowledgement());
        assert_eq!(notices.expires_in(start + Duration::from_secs(60)), None, "there is no timeout while awaiting confirmation");

        notices.warning("일부 값이 조정되었습니다", start + Duration::from_secs(61));
        assert_eq!(notices.current(start + Duration::from_secs(62)).unwrap().text, "일부 값이 조정되었습니다");
        notices.clear_transient();
        assert_eq!(notices.current(start + Duration::from_secs(62)).unwrap().text, "작업공간 상태를 확인해 주세요");
        assert_eq!(notices.acknowledge_workspace(), vec!["w:key".to_owned()]);
        assert!(notices.current(start + Duration::from_secs(62)).is_none());
    }
}
